import { openApp, shot } from "./browser";
const { ctx, page } = await openApp();
await page.goto("http://localhost:3300/presenter");
await page.waitForTimeout(1500);
await page.getByRole("button", { name: "New presentation" }).last().click();
await page.waitForTimeout(500);
await shot(page, "pres-modal");
await page.getByRole("button", { name: "Create" }).click();
await page.waitForTimeout(15000);
await shot(page, "pres-edit");
await page.getByRole("button", { name: /Template/ }).first().click();
await page.waitForTimeout(60000);
await shot(page, "pres-template");
await page.getByRole("button", { name: /Present/ }).first().click();
await page.waitForTimeout(3000);
await page.getByRole("button", { name: "Present" }).last().click();
await page.waitForTimeout(3000);
await shot(page, "pres-full");
await page.keyboard.press("ArrowRight");
await page.waitForTimeout(1500);
await shot(page, "pres-full2");
await ctx.close();
