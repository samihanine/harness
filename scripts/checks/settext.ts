import { Pptx } from "@server/pptx/ooxml";
import { readStoredFile, saveFile } from "@server/files";
import { slidePictures } from "@server/pptx/render";
import { closeBrowser } from "@server/capture/browser";
const doc = JSON.parse(await Bun.file(".local/pptx-doc.json").text());
const p = await Pptx.load((await readStoredFile(doc.fileId)).data);
await p.setText(5, "9", "**Pipeline** : 840 M$\n**Part du total** : 43 %\n**Opportunités** : 199");
await p.setText(5, "12", "À retenir\nEast porte plus de **4 dollars sur 10** du pipeline.");
const out = await p.save();
const [pic] = await slidePictures(out, [5]);
await Bun.write(".local/settext.png", pic);
await closeBrowser();
