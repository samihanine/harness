import { Pptx } from "@server/pptx/ooxml";
const p = await Pptx.load(new Uint8Array(await Bun.file(".local/check.pptx").arrayBuffer()));
const s = await p.structure();
console.log(s.length, JSON.stringify(s[3]).slice(0, 500));
const title = s[3].shapes.find((x) => x.text?.includes("Example"))!;
await p.setText(4, title.id, "Changed title");
const n = await p.duplicateSlide(4);
await p.moveSlide(n, 2);
await p.addPicture(2, new Uint8Array(await Bun.file(".local/check-5.png").arrayBuffer()), { x: 7, y: 2, w: 5 });
const out = await p.save();
await Bun.write(".local/check2.pptx", out);
const q = await Pptx.load(out);
const s2 = await q.structure();
console.log(s2.length, s2[1].shapes.map((x) => `${x.id}:${x.kind}:${x.text?.slice(0, 20) ?? ""}`).join(" | "));
